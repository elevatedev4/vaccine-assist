#!/usr/bin/env node
// Parses the "Macro codes" sheet of the pharmacy's v-macro-codes.xlsx
// formulary export into supabase/seed/vaccines.sql.
//
// The source .xlsx is NEVER committed to this repo (it's the pharmacy's
// live pricing/formulary export) — only this script and its generated
// output are. Run it again any time the formulary changes:
//
//   npm run seed:formulary -- /path/to/v-macro-codes.xlsx
//
// Defaults to reading from the path below if no argument is given (the
// scratchpad location used for the initial phase-1 seed).
//
// Deliberately does NOT touch the "Current lots" sheet — that's live
// inventory, entered through the app later, never seeded from a file.

import xlsx from "xlsx";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { parseFormularyRows } from "./lib/formulary-parser.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const DEFAULT_INPUT =
  "/private/tmp/claude-501/-Users-willanderson-claude/7e0755aa-ff16-406d-a09a-fc2debaa002e/scratchpad/vaccine-assist/v-macro-codes.xlsx";
const DEFAULT_OUTPUT = path.join(__dirname, "..", "..", "supabase", "seed", "vaccines.sql");

function sqlString(value) {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlInt(value) {
  return value === null || value === undefined ? "null" : String(value);
}

function buildSql(vaccines) {
  const header = `-- Generated by cloud/scripts/parse-formulary.mjs from the pharmacy's
-- v-macro-codes.xlsx "Macro codes" sheet — public drug/pricing data, safe
-- to commit. Do NOT commit the source .xlsx itself. Re-run
-- \`npm run seed:formulary -- /path/to/v-macro-codes.xlsx\` any time the
-- formulary changes; this file is regenerated in full each time.
--
-- ${vaccines.length} distinct vaccines (deduped by short_code, cross-checked
-- against ndc+name — see cloud/scripts/lib/formulary-parser.mjs).

`;

  const values = vaccines
    .map(
      (v) =>
        `  (${sqlString(v.name)}, ${sqlString(v.ndc)}, ${sqlString(v.dose)}, ${sqlString(
          v.shortCode
        )}, ${sqlInt(v.cashPriceCents)}, true)`
    )
    .join(",\n");

  const statement = `insert into vaccine (name, ndc, dose, short_code, cash_price_cents, active)
values
${values}
on conflict (short_code) do update set
  name = excluded.name,
  ndc = excluded.ndc,
  dose = excluded.dose,
  cash_price_cents = excluded.cash_price_cents,
  active = true,
  updated_at = now();
`;

  return header + statement;
}

function main() {
  const inputPath = process.argv[2] ?? DEFAULT_INPUT;
  const outputPath = process.argv[3] ?? DEFAULT_OUTPUT;

  console.log(`Reading formulary from ${inputPath}`);
  const workbook = xlsx.readFile(inputPath);
  const sheet = workbook.Sheets["Macro codes"];
  if (!sheet) {
    throw new Error('Sheet "Macro codes" not found in workbook.');
  }

  const rawRows = xlsx.utils.sheet_to_json(sheet, { header: 1, defval: null, raw: true });
  const { vaccines, warnings } = parseFormularyRows(rawRows);

  vaccines.sort((a, b) => a.name.localeCompare(b.name));

  for (const warning of warnings) {
    console.warn(`WARNING: ${warning}`);
  }

  const sql = buildSql(vaccines);
  writeFileSync(outputPath, sql, "utf8");
  console.log(`Wrote ${vaccines.length} vaccines to ${outputPath}`);
}

main();

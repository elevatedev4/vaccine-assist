#!/usr/bin/env node
// Emits supabase/seed/eligibility_rules.sql from the hand-decoded rules
// in scripts/lib/eligibility-rules-data.mjs (see that file's header for
// how each rule was read off vaccine-add-new.mxe's CASE blocks).
//
// Unlike parse-formulary.mjs, there's no source file to re-read here —
// the .mxe was decoded once by hand into eligibility-rules-data.mjs.
// Run this again after editing that file to regenerate the seed SQL:
//
//   npm run seed:eligibility

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { ELIGIBILITY_RULES } from "./lib/eligibility-rules-data.mjs";
import { buildEligibilityDeleteStatement, buildEligibilitySqlStatements } from "./lib/eligibility-sql.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT_PATH = path.join(__dirname, "..", "..", "supabase", "seed", "eligibility_rules.sql");

function main() {
  const header = `-- Generated by cloud/scripts/build-eligibility-seed.mjs from the rules
-- hand-decoded in cloud/scripts/lib/eligibility-rules-data.mjs (source:
-- vaccine-add-new.mxe's 24+ age/eligibility CASE blocks). Re-run
-- \`npm run seed:eligibility\` after editing that file.
--
-- ${ELIGIBILITY_RULES.length} rules. Each INSERT is a select-by-short_code
-- join against the vaccine table (see supabase/seed/vaccines.sql) — a
-- rule whose short_code isn't in the current formulary inserts zero rows
-- rather than failing. See eligibility-rules-data.mjs for the two CASE
-- blocks deliberately NOT seeded here (medicarehomevisit, DEFAULT CASE)
-- and every short_code-mapping judgment call.

`;

  const deleteStatement = buildEligibilityDeleteStatement(ELIGIBILITY_RULES);
  const inserts = buildEligibilitySqlStatements(ELIGIBILITY_RULES);

  const sql = header + deleteStatement + "\n\n" + inserts.join("\n\n") + "\n";
  writeFileSync(OUTPUT_PATH, sql, "utf8");
  console.log(`Wrote ${ELIGIBILITY_RULES.length} eligibility rules to ${OUTPUT_PATH}`);
}

main();
